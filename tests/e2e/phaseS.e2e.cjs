// Phase S Playwright: Fund Debt tab: loans, ladder, extension tests, rate
// exposure and caps, lenders, refinance planner, Excel. Fictional fixture;
// Supabase mocked.
const { chromium } = require("playwright");
const FX = require("./fixture.cjs");
const S = FX.outDir();
const data = FX.workspaceData();
data.deals = data.deals.map((d) => (d.id === "sample-deal-2" ? { ...d, inputs: { ...d.inputs, floatingRate: false, interestRatePct: 6.25 } } : d.id === "sample-deal-4" ? { ...d, inputs: { ...d.inputs, covenants: { minDscr: 9 } } } : d));
const now = Math.floor(Date.now() / 1000);
const b64 = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
const jwt = `${b64({ alg: "HS256" })}.${b64({ sub: "u1", email: "t@example.com", role: "authenticated", exp: now + 3600, aud: "authenticated" })}.sig`;
const sess = { access_token: jwt, token_type: "bearer", expires_in: 3600, expires_at: now + 3600, refresh_token: "r", user: { id: "u1", email: "t@example.com" } };
const ws = { id: "w1", name: "Model Fund I", version: 1, data, updated_at: new Date().toISOString(), updated_by_email: "t@example.com" };
let saves = 0;
let fails = 0;
const check = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fails++; };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1600, height: 1200 }, acceptDownloads: true });
  const errs = [];
  await ctx.addInitScript((v) => localStorage.setItem("sb-nydqmigxorahfkfpkjnq-auth-token", v), JSON.stringify(sess));
  await ctx.route("**/nydqmigxorahfkfpkjnq.supabase.co/**", (r) => {
    const req = r.request(); const u = req.url(); const acc = req.headers()["accept"] || "";
    let body = "[]";
    if (u.includes("/rpc/claim_invites")) body = "0";
    else if (u.includes("/rpc/save_workspace")) { saves++; body = String(++ws.version); }
    else if (u.includes("/auth/v1/user")) body = JSON.stringify(sess.user);
    else if (u.includes("/workspace_members")) body = JSON.stringify([{ workspace_id: "w1", role: "owner", email: "t@example.com" }]);
    else if (u.includes("/workspaces")) body = acc.includes("vnd.pgrst.object") ? JSON.stringify(ws) : JSON.stringify([ws]);
    r.fulfill({ status: 200, contentType: "application/json", body });
  });
  await ctx.route("**/maps.google.com/**", (r) => r.fulfill({ status: 200, contentType: "text/html", body: "<html></html>" }));
  const p = await ctx.newPage();
  p.on("pageerror", (e) => errs.push(e.message));
  await p.goto(FX.BASE_URL);
  await p.waitForTimeout(3500);
  const pm = p.getByRole("group", { name: "Portfolio Management" });
  const tabs = await pm.getByRole("button").allInnerTexts();
  check(tabs.findIndex((t) => /^Fund Debt/.test(t)) === tabs.findIndex((t) => /^GP Economics/.test(t)) + 1 && tabs.findIndex((t) => /^GP Economics/.test(t)) === tabs.findIndex((t) => /^Fund Return/.test(t)) + 1, "Fund Debt after Fund Return and GP Economics");
  const before = saves;
  await pm.getByRole("button", { name: "Fund Debt" }).click();
  await p.waitForTimeout(1500);
  const fdv = p.getByTestId("fund-debt");
  const sum = await p.getByTestId("debt-summary").innerText();
  check(/Debt\s*\$\d+\.\d\dM/.test(sum) && /Weighted DSCR\s*\d\.\d\dx/.test(sum) && /Floating/.test(sum), `summary: ${sum.replace(/\s+/g, " ").slice(0, 100)}`);
  const rows = p.getByTestId("debt-loan-row");
  check((await rows.count()) >= 9, `a row per loan (${await rows.count()})`);
  const r2 = await rows.filter({ hasText: "Route 9 Small Bay" }).innerText();
  check(/Fixed/.test(r2) && /6\.25%/.test(r2), "a fixed-rate loan shows its rate");
  check(/Fails: DSCR/.test(await rows.filter({ hasText: "Ridgeway Trade Center" }).getByTestId("ext-test").innerText()), "a loan whose covenant isn't met fails its extension test");
  check(/Passes/.test(await rows.filter({ hasText: "Airport Flex Park" }).getByTestId("ext-test").innerText()), "others pass");
  check((await p.getByTestId("ladder-year").count()) >= 2, "maturity ladder by year (current and fully extended)");
  const rt = await p.getByTestId("debt-rates").innerText();
  check(/Fixed rate/.test(rt) && /Floating, capped/.test(rt) && /Expires/.test(rt), "rate exposure and cap expiries");
  check(/HHI/.test(await p.getByTestId("debt-lenders").innerText()), "lender concentration");
  const refi = p.getByTestId("debt-refi");
  const r0 = await p.getByTestId("refi-result").innerText();
  await refi.getByLabel("Max LTV (%)").fill("50");
  await p.waitForTimeout(300);
  const r1 = await p.getByTestId("refi-result").innerText();
  check(r0 !== r1 && /LTV binds/.test(r1), "refinance planner reacts (LTV binds at 50%)");
  const [dl] = await Promise.all([p.waitForEvent("download"), fdv.getByRole("button", { name: "Excel", exact: true }).click()]);
  check(/fund-debt-.*\.xlsx$/.test(dl.suggestedFilename()), "Excel export");
  // ── Part 2: certificates and PDFs ──
  const [dp] = await Promise.all([p.waitForEvent("download"), fdv.getByRole("button", { name: "PDF", exact: true }).click()]);
  check(/fund-debt-.*\.pdf$/.test(dp.suggestedFilename()), "Fund Debt PDF");
  const certs = p.getByTestId("debt-certs");
  const lastQ = await certs.getByLabel("Certificate quarter").inputValue();
  const nCert = await p.getByTestId("cert-row").count();
  check(/-(03-31|06-30|09-30|12-31)$/.test(lastQ) && nCert >= 7 && nCert <= (await rows.count()), `a certificate row per loan in place at ${lastQ} (${nCert})`);
  check(/Breach/.test(await p.getByTestId("cert-row").filter({ hasText: "Ridgeway Trade Center" }).innerText()) && /In compliance/.test(await p.getByTestId("cert-row").filter({ hasText: "Airport Flex Park" }).innerText()), "compliance per loan (a covenant breach shown)");
  await certs.getByLabel("Certificate loan").selectOption({ label: "Airport Flex Park" });
  await p.waitForTimeout(300);
  check((await p.getByTestId("cert-row").count()) === 1, "one loan");
  const [c1] = await Promise.all([p.waitForEvent("download"), certs.getByRole("button", { name: "Certificates PDF" }).click()]);
  check(/^covenant-certificates-Airport-Flex-Park-\d{4}-\d{2}-\d{2}\.pdf$/.test(c1.suggestedFilename()), `certificate PDF: ${c1.suggestedFilename()}`);
  const [c2] = await Promise.all([p.waitForEvent("download"), certs.getByRole("button", { name: "Certificates Excel" }).click()]);
  check(/\.xlsx$/.test(c2.suggestedFilename()), "certificate Excel");
  await certs.getByLabel("Certificate quarter").selectOption({ index: 2 });
  await certs.getByLabel("Certificate loan").selectOption("");
  await p.waitForTimeout(300);
  check((await p.getByTestId("cert-row").count()) >= 1, "an earlier quarter");

  await p.getByRole("button", { name: "Home", exact: true }).click();
  await p.waitForTimeout(800);
  check((await p.getByTestId("lane").filter({ hasText: "Portfolio Management" }).getByRole("button", { name: "Open Fund Debt" }).count()) === 1, "Home's Portfolio Management lane links to Fund Debt");
  check(/Covenant breach: DSCR [\d.]+x < 9\.00x \(Ridgeway Trade Center\)/.test(await p.getByTestId("attention").innerText()), "Home: the covenant breach is on the attention list");
  await p.waitForTimeout(500);
  check(saves === before, "read-only: nothing saved");
  await p.screenshot({ path: `${S}/fund-debt.png` });
  check(errs.length === 0, `no page errors${errs.length ? ": " + errs.slice(0, 2).join(" / ") : ""}`);
  await b.close();
  console.log(fails ? `${fails} FAILED` : "ALL PASS");
  process.exitCode = fails ? 1 : 0;
})();
