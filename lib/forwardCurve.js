// The built-in snapshot as a curve object; an imported Pensford export
// (lib/pensfordImport.js) has the same shape and replaces it per deal.
export const DEFAULT_CURVE = {
  source: FORWARD_CURVE_SOURCE,
  asOf: FORWARD_CURVE_AS_OF,
  points: FORWARD_CURVE,
};

export const CURVE_INDICES = {
  termSofr1M: { label: "1-Month Term SOFR", col: 1 },
  avgSofr30D: { label: "30D Average SOFR (NY Fed)", col: 2 },
};

function addYearsISO(iso, n) {
  const [y, m, d] = iso.split("-").map(Number);
  const out = new Date(Date.UTC(y + n, m - 1, d));
  if (out.getUTCMonth() !== m - 1) out.setUTCDate(0);
  return out.toISOString().slice(0, 10);
}

function monthsBetween(fromISO, toISO) {
  const [y1, m1] = fromISO.split("-").map(Number);
  const [y2, m2] = toISO.split("-").map(Number);
  return Math.max(0, (y2 - y1) * 12 + (m2 - m1));
}

// Average projected rate for each year of a hold starting on startISO:
// year k averages the monthly resets dated in [start + (k-1) yrs, start + k yrs).
// Months before the curve's first reset count at that first reset (the curve
// starts at its as-of date); a year entirely past the last reset uses the last.
export function annualCurveForHold(startISO, holdYears, index = "termSofr1M", curve = DEFAULT_CURVE) {
  const col = CURVE_INDICES[index].col;
  const pts = curve.points;
  const first = pts[0];
  const last = pts[pts.length - 1];
  return Array.from({ length: Math.max(1, Math.round(holdYears)) }, (_, k) => {
    const from = addYearsISO(startISO, k);
    const to = addYearsISO(startISO, k + 1);
    if (to <= first[0]) return first[col];
    if (from > last[0]) return last[col];
    const vals = pts.filter((p) => p[0] >= from && p[0] < to).map((p) => p[col]);
    if (from < first[0]) {
      const early = Math.min(12, monthsBetween(from, first[0]));
      for (let i = 0; i < early; i++) vals.push(first[col]);
    }
    if (!vals.length) return last[col];
    return +(vals.reduce((s, v) => s + v, 0) / vals.length).toFixed(4);
  });
}
